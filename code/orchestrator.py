"""Explicit sequential orchestration for all six deletion-audit agents."""

from __future__ import annotations

from pathlib import Path

from agents.authorization_agent import AuthorizationAgent
from agents.evidence_agent import EvidenceInvestigationAgent
from agents.identity_agent import IdentityResolutionAgent
from agents.policy_auditor import PolicyRiskAuditor
from agents.remediation_agent import RemediationPlanningAgent
from agents.verification_agent import IndependentVerificationAgent
from config import Settings
from llm.gemini_client import GeminiService
from llm.usage_tracker import UsageTracker
from models import CaseResult, DeletionRequest
from tools.dataset_loader import case_sort_key, load_evidence_manifest, load_requests, parse_time, read_csv
from tools.evidence_indexer import EvidenceIndex
from tools.identity_resolver import IdentityResolver
from tools.output_validator import write_atomic
from tools.policy_engine import PolicyEngine


class DeletionAuditOrchestrator:
    """Runs one case at a time; no agent shares hidden mutable state with another."""

    def __init__(self, settings: Settings) -> None:
        self.settings = settings
        dataset = settings.dataset_dir
        self.usage = UsageTracker()
        self.llm = GeminiService(settings, self.usage)
        self.requests = load_requests(dataset)
        self.evidence_files = load_evidence_manifest(dataset)
        self.activity_rows = read_csv(dataset / "system_activity.csv")
        self.audit_rows = read_csv(dataset / "user_audit_log.csv")
        identities = read_csv(dataset / "user_identities.csv")
        self.index = EvidenceIndex(dataset, self.evidence_files)
        self.index.build()
        self.index.enrich_identity_links(self.activity_rows)
        resolver = IdentityResolver(identities, self.audit_rows, parse_time)
        policy = PolicyEngine(read_csv(dataset / "deletion_rules.csv"))
        self.authorize = AuthorizationAgent(self.llm)
        self.resolve = IdentityResolutionAgent(resolver)
        self.investigate = EvidenceInvestigationAgent(self.index)
        self.audit = PolicyRiskAuditor(policy)
        self.plan = RemediationPlanningAgent(policy)
        self.verify = IndependentVerificationAgent()

    def run_case(self, request: DeletionRequest) -> CaseResult:
        # Required strict order: authorize -> identity -> evidence -> policy -> plan -> verify.
        authorization = self.authorize.run(request)
        if not authorization.authorized:
            return CaseResult(request.case_id, "NOT_APPLICABLE", [], [authorization.rationale])
        identity = self.resolve.run(request)
        if identity is None:
            # Do not manufacture identity linkage or evidence references.
            return CaseResult(request.case_id, "INCOMPLETE", [], ["identity unresolved at audit cutoff"])
        observations = self.investigate.run(request, identity)
        findings = self.audit.run(observations)
        if findings:
            result = CaseResult(request.case_id, "INCOMPLETE", self.plan.run_incomplete(findings))
        else:
            checks = self.plan.run_complete(observations)
            result = CaseResult(request.case_id, "COMPLETE" if checks else "INCOMPLETE", checks,
                                [] if checks else ["no evidence-backed compliant state at audit cutoff"])
        evidence_ids = {item.file_id for item in self.evidence_files}
        evidence_ids |= {row["activity_id"] for row in self.activity_rows}
        evidence_ids |= {row["audit_id"] for row in self.audit_rows}
        errors = self.verify.run(result, evidence_ids)
        if errors:
            # One deterministic repair/revalidation pass: step numbering and ordering are regenerated by planners.
            result.diagnostics.extend(errors)
            if result.status == "INCOMPLETE":
                result.steps = self.plan.run_incomplete(findings)
            elif result.status == "COMPLETE":
                result.steps = self.plan.run_complete(observations)
            errors = self.verify.run(result, evidence_ids)
            if errors:
                raise ValueError(f"{request.case_id}: verification failed after one repair: {errors}")
        return result

    def run_all(self) -> list[CaseResult]:
        results = [self.run_case(request) for request in self.requests]
        return sorted(results, key=lambda result: case_sort_key(result.case_id))

    def write_output(self, results: list[CaseResult], output_path: Path | None = None) -> None:
        write_atomic(
            output_path or self.settings.output_path,
            results,
            [request.case_id for request in self.requests],
            {item.file_id for item in self.evidence_files},
            {row["activity_id"] for row in self.activity_rows},
            {row["audit_id"] for row in self.audit_rows},
        )
